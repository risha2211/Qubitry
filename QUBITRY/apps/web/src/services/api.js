const API_BASE = import.meta.env.VITE_API_URL || '/api';

function getHeaders() {
  const token = localStorage.getItem('qubitry_token');
  const headers = {
    'Content-Type': 'application/json'
  };
  if (token) {
    headers['Authorization'] = `Bearer ${token}`;
  }
  return headers;
}

async function request(endpoint, options = {}) {
  const url = endpoint.startsWith('http') ? endpoint : `${API_BASE}${endpoint}`;
  const config = {
    ...options,
    headers: {
      ...getHeaders(),
      ...(options.headers || {})
    }
  };

  try {
    const res = await fetch(url, config);
    const text = await res.text();
    let data;
    try {
      data = text ? JSON.parse(text) : {};
    } catch (e) {
      if (!res.ok) {
        throw new Error(`Server error (${res.status})`);
      }
      throw new Error(`Invalid server response`);
    }

    if (!res.ok) {
      throw new Error(data.message || `Request failed with status ${res.status}`);
    }
    return data;
  } catch (err) {
    console.error(`API Error [${options.method || 'GET'} ${url}]:`, err);
    throw err;
  }
}

export const authAPI = {
  async register({ username, email, password }) {
    return request('/auth/register', {
      method: 'POST',
      body: JSON.stringify({ username, email, password })
    });
  },

  async login({ email, password }) {
    return request('/auth/login', {
      method: 'POST',
      body: JSON.stringify({ email, password })
    });
  },

  async getMe() {
    return request('/auth/me', {
      method: 'GET'
    });
  }
};

export const circuitAPI = {
  async list({ search = '', tag = '' } = {}) {
    const params = new URLSearchParams();
    if (search) params.append('search', search);
    if (tag) params.append('tag', tag);
    const qs = params.toString() ? `?${params.toString()}` : '';
    return request(`/circuits${qs}`, {
      method: 'GET'
    });
  },

  async get(id) {
    return request(`/circuits/${id}`, {
      method: 'GET'
    });
  },

  async create(circuitData) {
    return request('/circuits', {
      method: 'POST',
      body: JSON.stringify(circuitData)
    });
  },

  async update(id, updates) {
    return request(`/circuits/${id}`, {
      method: 'PUT',
      body: JSON.stringify(updates)
    });
  },

  async delete(id) {
    return request(`/circuits/${id}`, {
      method: 'DELETE'
    });
  },

  async fork(id) {
    return request(`/circuits/${id}/fork`, {
      method: 'POST'
    });
  },

  async export(id, format = 'qasm') {
    return request(`/circuits/${id}/export?format=${format}`, {
      method: 'GET'
    });
  },

  async import(data, title) {
    return request('/circuits/import', {
      method: 'POST',
      body: JSON.stringify({ data, title })
    });
  }
};

/**
 * Client-side circuit code generators (allows exporting live unsaved circuit from Studio without delay)
 */
export function generateOpenQASM(circuit, version = 2) {
  const n = circuit.qubits || circuit.n || 2;
  const lines = [
    `// Generated by Qubitry - Quantum Circuit Studio`,
    `// Circuit: ${circuit.title || circuit.note?.name || 'Interactive Circuit'}`,
    `// Exported: ${new Date().toISOString()}`,
    `OPENQASM ${version === 3 ? '3.0' : '2.0'};`,
    `include "qelib1.inc";`,
    ``,
    `qreg q[${n}];`,
    `creg c[${n}];`,
    ``
  ];

  const sortedOps = [...(circuit.ops || [])].sort((a, b) => (a.s ?? 0) - (b.s ?? 0));
  for (const op of sortedOps) {
    const g = op.g;
    const qs = op.q;
    const p = op.p ? +(op.p).toFixed(4) : 0;
    switch (g) {
      case 'H': lines.push(`h q[${qs[0]}];`); break;
      case 'X': lines.push(`x q[${qs[0]}];`); break;
      case 'Y': lines.push(`y q[${qs[0]}];`); break;
      case 'Z': lines.push(`z q[${qs[0]}];`); break;
      case 'S': lines.push(`s q[${qs[0]}];`); break;
      case 'Sdg': lines.push(`sdg q[${qs[0]}];`); break;
      case 'T': lines.push(`t q[${qs[0]}];`); break;
      case 'Tdg': lines.push(`tdg q[${qs[0]}];`); break;
      case 'RX': lines.push(`rx(${p}) q[${qs[0]}];`); break;
      case 'RY': lines.push(`ry(${p}) q[${qs[0]}];`); break;
      case 'RZ': lines.push(`rz(${p}) q[${qs[0]}];`); break;
      case 'P': lines.push(`u1(${p}) q[${qs[0]}];`); break;
      case 'CX': lines.push(`cx q[${qs[0]}], q[${qs[1]}];`); break;
      case 'CY': lines.push(`cy q[${qs[0]}], q[${qs[1]}];`); break;
      case 'CZ': lines.push(`cz q[${qs[0]}], q[${qs[1]}];`); break;
      case 'SWAP': lines.push(`swap q[${qs[0]}], q[${qs[1]}];`); break;
      case 'CCX': lines.push(`ccx q[${qs[0]}], q[${qs[1]}], q[${qs[2]}];`); break;
      case 'CSWAP': lines.push(`cswap q[${qs[0]}], q[${qs[1]}], q[${qs[2]}];`); break;
      case 'M': lines.push(`measure q[${qs[0]}] -> c[${qs[0]}];`); break;
      case 'Reset': lines.push(`reset q[${qs[0]}];`); break;
      default: lines.push(`// Unsupported gate: ${g}`);
    }
  }
  return lines.join('\n');
}

export function generateQiskit(circuit) {
  const n = circuit.qubits || circuit.n || 2;
  const lines = [
    `# ==============================================================`,
    `# Generated by Qubitry - Quantum Circuit Studio`,
    `# Circuit: ${circuit.title || circuit.note?.name || 'Interactive Circuit'} (${n} qubits)`,
    `# ==============================================================`,
    `from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister, Aer, execute`,
    `import numpy as np`,
    ``,
    `qr = QuantumRegister(${n}, 'q')`,
    `cr = ClassicalRegister(${n}, 'c')`,
    `qc = QuantumCircuit(qr, cr, name='QubitryCircuit')`,
    ``
  ];

  const sortedOps = [...(circuit.ops || [])].sort((a, b) => (a.s ?? 0) - (b.s ?? 0));
  for (const op of sortedOps) {
    const g = op.g;
    const qs = op.q;
    const p = op.p ? +(op.p).toFixed(4) : 0;
    switch (g) {
      case 'H': lines.push(`qc.h(${qs[0]})`); break;
      case 'X': lines.push(`qc.x(${qs[0]})`); break;
      case 'Y': lines.push(`qc.y(${qs[0]})`); break;
      case 'Z': lines.push(`qc.z(${qs[0]})`); break;
      case 'S': lines.push(`qc.s(${qs[0]})`); break;
      case 'Sdg': lines.push(`qc.sdg(${qs[0]})`); break;
      case 'T': lines.push(`qc.t(${qs[0]})`); break;
      case 'Tdg': lines.push(`qc.tdg(${qs[0]})`); break;
      case 'RX': lines.push(`qc.rx(${p}, ${qs[0]})`); break;
      case 'RY': lines.push(`qc.ry(${p}, ${qs[0]})`); break;
      case 'RZ': lines.push(`qc.rz(${p}, ${qs[0]})`); break;
      case 'P': lines.push(`qc.p(${p}, ${qs[0]})`); break;
      case 'CX': lines.push(`qc.cx(${qs[0]}, ${qs[1]})`); break;
      case 'CY': lines.push(`qc.cy(${qs[0]}, ${qs[1]})`); break;
      case 'CZ': lines.push(`qc.cz(${qs[0]}, ${qs[1]})`); break;
      case 'SWAP': lines.push(`qc.swap(${qs[0]}, ${qs[1]})`); break;
      case 'CCX': lines.push(`qc.ccx(${qs[0]}, ${qs[1]}, ${qs[2]})`); break;
      case 'CSWAP': lines.push(`qc.cswap(${qs[0]}, ${qs[1]}, ${qs[2]})`); break;
      case 'M': lines.push(`qc.measure(${qs[0]}, ${qs[0]})`); break;
      case 'Reset': lines.push(`qc.reset(${qs[0]})`); break;
    }
  }

  lines.push(``);
  lines.push(`backend = Aer.get_backend('aer_simulator')`);
  lines.push(`job = execute(qc, backend, shots=${circuit.shots || 1024})`);
  lines.push(`result = job.result()`);
  lines.push(`print("Counts:", result.get_counts(qc))`);
  return lines.join('\n');
}

export function generateCirq(circuit) {
  const n = circuit.qubits || circuit.n || 2;
  const lines = [
    `# ==============================================================`,
    `# Generated by Qubitry - Quantum Circuit Studio`,
    `# Circuit: ${circuit.title || circuit.note?.name || 'Interactive Circuit'} (${n} qubits)`,
    `# ==============================================================`,
    `import cirq`,
    `import numpy as np`,
    ``,
    `qubits = cirq.LineQubit.range(${n})`,
    `circuit = cirq.Circuit()`,
    ``
  ];

  const sortedOps = [...(circuit.ops || [])].sort((a, b) => (a.s ?? 0) - (b.s ?? 0));
  for (const op of sortedOps) {
    const g = op.g;
    const qs = op.q;
    const p = op.p ? +(op.p).toFixed(4) : 0;
    switch (g) {
      case 'H': lines.push(`circuit.append(cirq.H(qubits[${qs[0]}]))`); break;
      case 'X': lines.push(`circuit.append(cirq.X(qubits[${qs[0]}]))`); break;
      case 'Y': lines.push(`circuit.append(cirq.Y(qubits[${qs[0]}]))`); break;
      case 'Z': lines.push(`circuit.append(cirq.Z(qubits[${qs[0]}]))`); break;
      case 'S': lines.push(`circuit.append(cirq.S(qubits[${qs[0]}]))`); break;
      case 'T': lines.push(`circuit.append(cirq.T(qubits[${qs[0]}]))`); break;
      case 'RX': lines.push(`circuit.append(cirq.rx(${p})(qubits[${qs[0]}]))`); break;
      case 'RY': lines.push(`circuit.append(cirq.ry(${p})(qubits[${qs[0]}]))`); break;
      case 'RZ': lines.push(`circuit.append(cirq.rz(${p})(qubits[${qs[0]}]))`); break;
      case 'CX': lines.push(`circuit.append(cirq.CNOT(qubits[${qs[0]}], qubits[${qs[1]}]))`); break;
      case 'CZ': lines.push(`circuit.append(cirq.CZ(qubits[${qs[0]}], qubits[${qs[1]}]))`); break;
      case 'SWAP': lines.push(`circuit.append(cirq.SWAP(qubits[${qs[0]}], qubits[${qs[1]}]))`); break;
      case 'CCX': lines.push(`circuit.append(cirq.TOFFOLI(qubits[${qs[0]}], qubits[${qs[1]}], qubits[${qs[2]}]))`); break;
      case 'CSWAP': lines.push(`circuit.append(cirq.FREDKIN(qubits[${qs[0]}], qubits[${qs[1]}], qubits[${qs[2]}]))`); break;
      case 'M': lines.push(`circuit.append(cirq.measure(qubits[${qs[0]}], key='m${qs[0]}'))`); break;
    }
  }

  lines.push(``);
  lines.push(`simulator = cirq.Simulator()`);
  lines.push(`result = simulator.run(circuit, repetitions=${circuit.shots || 1024})`);
  lines.push(`print(result)`);
  return lines.join('\n');
}

export function generateJSON(circuit) {
  return JSON.stringify(
    {
      format: 'qubitry-v1',
      exportedAt: new Date().toISOString(),
      circuit: {
        title: circuit.title || circuit.note?.name || 'Untitled Circuit',
        description: circuit.description || '',
        qubits: circuit.qubits || circuit.n || 2,
        tags: circuit.tags || [],
        shots: circuit.shots || 1024,
        ops: circuit.ops || []
      }
    },
    null,
    2
  );
}

